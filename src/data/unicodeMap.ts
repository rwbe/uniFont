interface GlyphData {
  baseChars: string[];
  styleVariants: string[][];
  reverseMap: Record<string, string>;
}

function parseGlyphTable(): GlyphData {
  const baseChars: string[] = [];
  const styleVariants: string[][] = [];
  const reverseMap: Record<string, string> = {};

  glyphTable.split('\n').forEach(line => {
    const variants = line.split(/\s+/).filter(Boolean);
    const [baseChar] = variants;
    baseChars.push(baseChar);

    variants.forEach((variant, styleIndex) => {
      reverseMap[variant] = baseChar;
      if (!styleVariants[styleIndex]) styleVariants[styleIndex] = [];
      styleVariants[styleIndex].push(variant);
    });
  });

  return { baseChars, styleVariants, reverseMap };
}

export const glyphData = parseGlyphTable();
